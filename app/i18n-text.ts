const translatedText: Record<Exclude<Locale, "ru">, Record<string, string>> = {
  en: englishText,
  fa: persianText,
  "zh-Hans": simplifiedChineseText,
  "zh-Hant": traditionalChineseText,
};

export function localizedText(source: string, locale: Locale): string {
  return locale === "ru" ? source : translatedText[locale][source] ?? source;
}

export function formatLocalizedText(source: string, locale: Locale, values: Record<string, string | number>): string {
  // One pass: an object's name containing braces must never become another placeholder.
  return localizedText(source, locale).replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}
